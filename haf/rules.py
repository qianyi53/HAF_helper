# -*- coding: utf-8 -*-
"""haf/rules.py — L2 筛选规则（外置配置，可由需求方直接修改关键词）

标签体系（裁定见 docs/问答对齐.md Q-L2-5）:
  证件类型: 许可证 / 境外注册登记确认书
  事件(文档级, 可多个): 颁发 / 延续 / 不予延续 / 变更 / 吊销 / 注销
  活动种类: 设计 / 制造 / 安装 / 无损检验 (可多选, 标题未注明留空)

规则设计原则（来自 M1 分析报告 docs/reports/2026-09-27-【分析】-M1筛选特征分析报告.md）:
  - 域门控: 关键词族唯一，实测零误检
  - 文档级事件: 只用标题判定（正文匹配会被内嵌语句污染）
  - 内嵌事件: 句级正则，从正文抽取，与文档级事件合并入同一标签族
"""
import re

# ---------- 1. 域门控 ----------
# 命中任一关键词 → 域内候选; 否则整篇排除(含: 核电厂运行/建造许可、放射性
# 废物许可、运输容器许可、质量保证大纲、核安全导则等, 裁定 Q-L2-1/Q-L2-2/Q-L2-3)
DOMAIN_GATE = re.compile(r"核安全设备|注册登记|单位资质")

# ---------- 2. 文档级事件规则（只匹配标题; 列表按优先级排列） ----------
# 注意: 规则顺序即优先级——"不予延续"必须先于"延续"，避免误标
TITLE_EVENT_RULES: list[tuple[str, re.Pattern]] = [
    ("不予延续", re.compile(r"不予(延续|批准|注册登记|许可)")),
    ("吊销",     re.compile(r"吊销")),
    ("注销",     re.compile(r"注销")),
    ("变更",     re.compile(r"变更")),
    ("延续",     re.compile(r"延续")),
    # 注意: 只认"颁发"字样。"批准延续/批准变更"中的"批准"是公文措辞而非
    # 颁发事件, 实测 0 篇域内标题含"批准/准予"但不含任何具体事件词, 无需兜底
    ("颁发",     re.compile(r"颁发")),
]

# ---------- 3. 证件类型规则（标题优先, 正文兜底; 先判注册登记再判许可证） ----------
CERT_TYPE_RULES: list[tuple[str, re.Pattern]] = [
    ("境外注册登记确认书", re.compile(r"注册登记确认书|境外单位注册登记")),
    ("许可证",             re.compile(r"核安全设备.{0,10}许可|许可.{0,10}核安全设备")),
]

# ---------- 4. 活动种类规则（标题） ----------
ACTIVITY_RULES: list[tuple[str, re.Pattern]] = [
    ("设计",     re.compile(r"设计")),
    ("制造",     re.compile(r"制造")),
    ("安装",     re.compile(r"安装")),
    ("无损检验", re.compile(r"无损检验")),
]

# ---------- 5. 内嵌事件规则（句级, 正文; 可命中多个, 均并入事件标签族） ----------
# 每条: (事件标签, 提取正则, 说明)
EMBEDDED_EVENT_RULES: list[tuple[str, re.Pattern, str]] = [
    # "…同时注销××持有的民用核安全设备制造许可证…" (句界内匹配, 兼容境外单位长英文名)
    ("注销", re.compile(r"同时注销[^。；\n]{0,200}?(?:许可证|确认书)"),
     "换证时同时注销原证"),
    # "…××注册登记范围变更的申请文件进行了审查…"
    ("变更", re.compile(r"注册登记范围变更|注册登记.{0,6}变更"),
     "境外注册登记范围变更(合并发文)"),
    # "…《关于民用核安全设备制造许可证单位名称变更的申请》…"
    ("变更", re.compile(r"(单位|公司)名称变更"),
     "持证单位名称变更(合并发文)"),
]

# 规则版本: 打标结果 meta 中记录, 便于追溯是哪一版规则产出
RULES_VERSION = "v1.1 (2026-09-27, 裁定 Q-L2-5; 注释编号改按架构分层)"
